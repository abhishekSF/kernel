/* Build-time guards for Kernel's "nothing leaves this browser" promise.
 *
 * 1. A Content-Security-Policy meta tag. `connect-src 'none'` makes the
 *    browser refuse every fetch, XHR, WebSocket, EventSource and beacon the
 *    page could attempt, so a future dependency can't phone home either.
 * 2. A service worker that precaches the built app, so Kernel keeps working
 *    with no connection. It only answers same-origin GETs for Kernel's own
 *    files and never contacts any other host.
 *
 * Both are build-only: the dev server needs a WebSocket for hot reload.
 */

import { createHash } from "node:crypto";

export const CSP = [
  "default-src 'none'",
  "script-src 'self'",
  // React writes inline style attributes for the mode colours and hourglass.
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'none'",
  "media-src 'self'",
  "manifest-src 'self'",
  "worker-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
].join("; ");

const PUBLIC_FILES = ["./", "index.html", "manifest.webmanifest", "icon.svg"];

export function serviceWorkerSource(files) {
  const precache = [...PUBLIC_FILES, ...files];
  const version = createHash("sha256").update(precache.join("\n")).digest("hex").slice(0, 12);
  return `/* Generated by tooling/local-first.js. Serves Kernel's own files from a local cache. */
const CACHE = "kernel-${version}";
const PRECACHE = ${JSON.stringify(precache)};
const scoped = (path) => new URL(path, self.registration.scope).href;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(PRECACHE.map(scoped))).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("kernel-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  if (new URL(req.url).origin !== self.location.origin) return;

  if (req.mode === "navigate") {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(scoped("index.html"), copy));
          }
          return res;
        })
        .catch(() => caches.match(scoped("index.html")))
    );
    return;
  }

  event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;
}

/** @returns {import("vite").Plugin} */
export function localFirst() {
  return {
    name: "kernel-local-first",
    apply: "build",
    transformIndexHtml() {
      return [
        {
          tag: "meta",
          attrs: { "http-equiv": "Content-Security-Policy", content: CSP },
          injectTo: "head-prepend",
        },
        { tag: "meta", attrs: { name: "referrer", content: "no-referrer" }, injectTo: "head" },
        { tag: "link", attrs: { rel: "manifest", href: "./manifest.webmanifest" }, injectTo: "head" },
      ];
    },
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => f !== "index.html").sort();
      this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorkerSource(files) });
    },
  };
}
